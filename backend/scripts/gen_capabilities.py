"""Generate internal/auth/capabilities_gen.go from Django's accounts/capabilities.py.

Run from the Django checkout (../kura-django/backend):  uv run python ../../kura/backend/scripts/gen_capabilities.py
Keeps the Go capability matrix identical to Django's single source of truth.
"""
import os
import sys

sys.path.insert(0, os.getcwd())
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings.local")
import django  # noqa: E402

django.setup()
from accounts.capabilities import (  # noqa: E402
    PERMISSION_CATALOG,
    ROLE_CAPABILITIES,
    ROLE_META,
)

out = os.path.join(os.path.dirname(__file__), "..", "internal", "auth", "capabilities_gen.go")
q = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'  # noqa: E731
lines = [
    "// Code generated by scripts/gen_capabilities.py from Django; DO NOT EDIT.",
    "",
    "package auth",
    "",
    "// PermissionCatalog mirrors accounts/capabilities.PERMISSION_CATALOG.",
    "var PermissionCatalog = []Permission{",
]
for code, name, module, desc in PERMISSION_CATALOG:
    lines.append(f"\t{{Code: {q(code)}, Name: {q(name)}, Module: {q(module)}, Description: {q(desc)}}},")
lines += ["}", "", "// RoleMeta mirrors ROLE_META.", "var RoleMeta = map[string]RoleInfo{"]
for code, meta in ROLE_META.items():
    lines.append(f"\t{q(code)}: {{Name: {q(meta['name'])}, Description: {q(meta['description'])}}},")
lines += ["}", "", '// roleGrants mirrors ROLE_CAPABILITIES ("*" = every permission).',
          "var roleGrants = map[string][]string{"]
for role, grant in ROLE_CAPABILITIES.items():
    if grant == "*":
        lines.append(f'\t{q(role)}: {{"*"}},')
    else:
        lines.append(f"\t{q(role)}: {{{', '.join(q(c) for c in sorted(grant))}}},")
lines += ["}", ""]
open(out, "w").write("\n".join(lines))
print("wrote", os.path.normpath(out), len(PERMISSION_CATALOG), "permissions", len(ROLE_CAPABILITIES), "roles")
